from jsontext import load, locate, put, skip
from physics import ASSETS
from shape import save

GENERATED = "// Generated by `bin/model build` from the model; a build rewrites these values: "
PATCHES = ASSETS / "patches"
recorded = {}


def merged(into, *more):
    for values in more:
        for key, value in values.items():
            if isinstance(value, dict) and isinstance(into.get(key), dict):
                merged(into[key], value)
            else:
                into[key] = value
    return into


def path_of(vessel):
    return ASSETS / "entities/vessel" / f"{vessel}.json"


def read(vessel):
    return load(path_of(vessel))


def record(vessel, values):
    """Writes what the model measures into the vessel's entity, or for a vanilla boat into the patches that give her
    each behaviour, every other character of the file as it was; each place written names what it holds first."""
    if path_of(vessel).exists():
        write(path_of(vessel), [], values)
        return
    for code, config in values.pop("behaviorConfigs", {}).items():
        path, at = patched(vessel, code)
        write(path, [at, "value"], config)
    if values:
        raise ValueError(f"{vessel} is vanilla's: her own {', '.join(values)} are not ours to write")


def patched(vessel, code):
    for path in sorted(PATCHES.glob("*.json")):
        for at, op in enumerate(load(path)):
            if op.get("file") == f"game:entities/nonliving/boat-{vessel}.json" and op.get("path") == f"/behaviorConfigs/{code}":
                return path, at
    raise KeyError(f"no patch gives boat-{vessel} {code}")


def write(path, root, values):
    text = path.read_text()
    found = list(leaves(values))
    shown = [([step if isinstance(step, str) else "[]" for step in at], value) for at, value in found]
    for at, value in found:
        text = put(text, root + at, value)
    names = recorded.setdefault((path, tuple(root)), {})
    for at, _ in shown:
        names.setdefault(".".join(step for step in at[:-1] if step != "behaviorConfigs").replace(".[]", "[]"), {})[at[-1]] = None
    listed = "; ".join(f"{parent}: {', '.join(keys)}" if parent else ", ".join(keys) for parent, keys in names.items())
    save(path, headed(text, root, GENERATED + listed))


def leaves(values, at=()):
    for key, value in values.items():
        if isinstance(value, dict):
            yield from leaves(value, (*at, key))
        else:
            yield [*at, key], value


def headed(text, root, header):
    start = locate(text, root)
    first = text.find(GENERATED, start)
    if first >= 0 and first < skip(text, start + 1):
        text = text[:text.rfind("\n", 0, first) + 1] + text[text.index("\n", first) + 1:]
    key = skip(text, start + 1)
    line = text.rfind("\n", 0, key) + 1
    return text[:line] + text[line:key] + header + "\n" + text[line:]
